// measure-bazel.mjs — candidate 8: Bazel's declared graph (test-selection-exploration.md).
//
// Usage: node bench/test-selection/measure-bazel.mjs --repo <sandbox> --sets <audit.json> --truth <ground-truth.json>
//        --bazel <bazelisk binary> --home <dir for bazelisk's downloads and bazel's output root> --out <file.json>
//
// Bazel selects from DECLARATIONS: one target per test, its recorded reads inside the repository (candidate 4's sets) as
// srcs, and `bazel query 'rdeps(//:all, set(<changed file>))'` answers which targets depend on a change, without running
// anything and without bazel-diff (so no Java). On Windows Bazel has no sandbox, so nothing enforces a declaration here;
// that part of Bazel is Linux/macOS only. Kept out of the operator's profile: BAZELISK_HOME and --output_user_root point
// under --home, and the server is shut down at the end, since a running server would hold the sandbox open.

import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { requireIsolated } from './guard.mjs';

const arg = (k) => { const i = process.argv.indexOf(`--${k}`); return i > 0 ? process.argv[i + 1] : null; };
const repo = path.resolve(arg('repo') ?? (() => { throw new Error('--repo is required'); })());
requireIsolated(repo);
const { sets } = JSON.parse(fs.readFileSync(path.resolve(arg('sets')), 'utf8'));
const truth = JSON.parse(fs.readFileSync(path.resolve(arg('truth')), 'utf8'));
const bazel = path.resolve(arg('bazel'));
const home = path.resolve(arg('home'));
const out = path.resolve(arg('out') ?? 'bazel.json');
fs.mkdirSync(home, { recursive: true });

const ids = Object.fromEntries(truth.sample.map((t, i) => [t, `t${i}`]));
const label = (f) => `//:${f}`;
const lines = ['# Generated by bench/test-selection/measure-bazel.mjs: one target per test file, its recorded reads.'];
for (const t of truth.sample) {
  // INSIDE THE REPOSITORY ONLY: across drives path.relative gives an absolute path, not one starting with '..', so node's
  // own files under C:\Program Files passed a `..` filter and Bazel refused them ("invalid label 'C:/Progr...'").
  const inRepo = (f) => !f.startsWith('..') && !/^[A-Za-z]:|^[\\/]/.test(f);
  const files = [...new Set([...(sets[t]?.load ?? []), ...(sets[t]?.read ?? [])])].filter(inRepo).sort();
  lines.push(`filegroup(name = "${ids[t]}", srcs = [${files.map((f) => JSON.stringify(f)).join(', ')}])`);
}
fs.writeFileSync(path.join(repo, 'BUILD.bazel'), `${lines.join('\n')}\n`);
fs.writeFileSync(path.join(repo, 'MODULE.bazel'), 'module(name = "ts_bazel")\n');
const outputRoot = path.join(home, 'output-root').replaceAll('\\', '/');
fs.writeFileSync(path.join(repo, '.bazelrc'), `startup --output_user_root=${outputRoot}\ncommon --enable_bzlmod\n`);

const env = { ...process.env, BAZELISK_HOME: path.join(home, 'bazelisk') };
const run = (args) => {
  const started = Date.now();
  const r = spawnSync(bazel, args, { cwd: repo, env, encoding: 'utf8', maxBuffer: 1 << 26, shell: process.platform === 'win32' });
  return { status: r.status, ms: Date.now() - started, stdout: r.stdout ?? '', stderr: r.stderr ?? '' };
};

const version = run(['--version']);
console.log(`bazel: ${(version.stdout || version.stderr).split(/\r?\n/)[0]}`);
const result = { version: (version.stdout || '').trim(), candidate: {} };
try {
  const rows = [];
  for (const c of truth.changes) {
    const q = run(['query', `rdeps(//:all, set(${label(c.file)}))`, '--output=label', '--keep_going', '--noshow_progress']);
    const targets = q.stdout.split(/\r?\n/).map((l) => l.trim()).filter((l) => /^\/\/:t\d+$/.test(l)).map((l) => l.slice(3));
    const selected = truth.sample.filter((t) => targets.includes(ids[t]));
    const err = q.status === 0 ? null : (q.stderr.match(/ERROR:[^\n]*/) ?? [null])[0];
    rows.push({ id: c.id, kind: c.kind, affected: c.affected.length, selected: selected.length,
      missed: c.affected.filter((t) => !selected.includes(t)), over: selected.filter((t) => !c.affected.includes(t)).length, ms: q.ms, error: err });
    console.log(`  ${c.id} ${c.kind.padEnd(34)} affected ${c.affected.length}  selected ${selected.length}  missed ${rows.at(-1).missed.length}  over ${rows.at(-1).over}  (${(q.ms / 1000).toFixed(1)} s)${err ? `  [${err.slice(0, 90)}]` : ''}`);
  }
  result.candidate['C8-bazel-query'] = { misses: rows.reduce((n, x) => n + x.missed.length, 0), rows };
  console.log(`C8-bazel-query: ${result.candidate['C8-bazel-query'].misses} miss(es)`);
} finally {
  run(['shutdown']);
}
fs.writeFileSync(out, `${JSON.stringify(result, null, 2)}\n`);
